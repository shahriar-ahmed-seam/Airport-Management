END;
/

-- FUNCTION 3: TOTAL_PROFIT
CREATE OR REPLACE FUNCTION TOTAL_PROFIT(Code IN NUMBER)
RETURN NUMBER IS
    debit NUMBER(10);
    credit NUMBER(10);
    profit NUMBER(10);
BEGIN
    debit := TOTAL_DEBIT(Code);
    credit := TOTAL_CREDIT(Code);
    profit := credit - debit;
    RETURN profit;
EXCEPTION
   WHEN NO_DATA_FOUND THEN
      RETURN 0;
   WHEN OTHERS THEN
      RAISE;
END;
/

