-- FUNCTION 1: TOTAL_DEBIT
CREATE OR REPLACE FUNCTION TOTAL_DEBIT(Code IN NUMBER)
RETURN NUMBER IS 
   debit NUMBER(10);
BEGIN
   IF Code IS NOT NULL AND Code > 0 THEN
      SELECT NVL(SUM(Salary), 0) INTO debit FROM Employees WHERE ID = Code;
   ELSE
      SELECT NVL(SUM(Salary), 0) INTO debit FROM Employees;
   END IF;
   RETURN debit;
EXCEPTION
   WHEN NO_DATA_FOUND THEN
      RETURN 0;
   WHEN OTHERS THEN
      RAISE;
END;
/

-- Test Function 1
DECLARE 
  AMOUNT NUMBER(10);
BEGIN
  AMOUNT := TOTAL_DEBIT(5);
  DBMS_OUTPUT.PUT_LINE('Total Debit: ' || AMOUNT);
END;
/

-- FUNCTION 2: TOTAL_CREDIT
CREATE OR REPLACE FUNCTION TOTAL_CREDIT(Code IN NUMBER)
RETURN NUMBER IS 
   total_debit NUMBER(10);
   total_credit NUMBER(10);
BEGIN 
   total_debit := TOTAL_DEBIT(Code);
   total_credit := total_debit + 100000;
   RETURN total_credit;
EXCEPTION
   WHEN NO_DATA_FOUND THEN
      RETURN 100000;
   WHEN OTHERS THEN
      RAISE;
END;
/

