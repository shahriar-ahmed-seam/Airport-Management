-- FUNCTION 4: FIND_PLANE
CREATE OR REPLACE FUNCTION FIND_PLANE(FLIGHT IN NUMBER, TIME_VAL IN NUMBER)
RETURN VARCHAR2 IS 
   loc VARCHAR2(50);
BEGIN
   SELECT Place INTO loc 
   FROM Location
   WHERE (Flight_No = FLIGHT) AND (TIME_VAL >= Start_Time) AND (TIME_VAL <= End_Time);
   RETURN loc;
EXCEPTION
   WHEN NO_DATA_FOUND THEN 
      RETURN 'Not Found';
   WHEN OTHERS THEN
      RAISE; 
END;
/

